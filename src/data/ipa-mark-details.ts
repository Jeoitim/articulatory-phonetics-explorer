export function referenceForMark(symbol: string) {
  const keys = symbol
    .split(' / ')
    .map((s) =>
      s.replaceAll('◌', '').replaceAll('\u034f', '').normalize('NFD').trim(),
    );
  const records = keys
    .map((k) => ipaReferenceAudio[k])
    .filter((r) => r !== undefined);
  return {
    ipaNumber: [...new Set(records.map((r) => r.ipaNumber))]
      .filter(Boolean)
      .join(' / '),
    clips: records
      .flatMap((r) => r.clips)
      .filter((clip, i, all) => all.findIndex((c) => c.url === clip.url) === i),
  };
}
