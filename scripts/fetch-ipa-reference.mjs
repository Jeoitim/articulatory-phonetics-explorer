import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';

const sourcePage =
  'https://www.internationalphoneticassociation.org/IPAcharts/IPA_charts_TI/IPA_charts_TI.html#eng';
const sourceText = await readFile('src/data/ipa-reference-audio.ts', 'utf8');
const urls = [
  ...new Set(
    [
      ...sourceText.matchAll(
        /https:\/\/www\.internationalphoneticassociation\.org\/IPAcharts\/common_files\/sounds\/[^'"\s]+?\.mp3/g,
      ),
    ].map((match) => match[0]),
  ),
];
const targetDir = 'public/audio/ipa-reference';
await mkdir(targetDir, { recursive: true });
const refresh = process.argv.includes('--refresh');
const userAgent =
  process.env.IPA_AUDIO_USER_AGENT ||
  'ArticulatoryPhoneticsExplorer/1.0 (local educational project; https://localhost:3000/)';
const local = {};
const failed = [];
let next = 0;

async function cacheOne(url) {
  const name =
    createHash('sha256').update(url).digest('hex').slice(0, 16) + '.mp3';
  const path = `${targetDir}/${name}`;
  let cached = false;
  if (!refresh) {
    try {
      cached = (await stat(path)).size > 100;
    } catch {
      cached = false;
    }
  }
  if (!cached) {
    const response = await fetch(url, {
      signal: AbortSignal.timeout(30000),
      headers: { 'user-agent': userAgent, accept: 'audio/mpeg,audio/*;q=0.8' },
    });
    if (!response.ok) throw Error(`${response.status} ${response.statusText}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (
      bytes.length <= 100 ||
      bytes.subarray(0, 3).toString('ascii') !== 'ID3'
    ) {
      // Some valid MPEG files begin with an MPEG frame rather than an ID3 tag.
      // The content-type and non-empty body are the reliable checks here.
      const type = response.headers.get('content-type') || '';
      if (!type.includes('audio') && bytes.length < 1024)
        throw Error('response is not an audio file');
    }
    await writeFile(path, bytes);
  }
  local[url] = `/audio/ipa-reference/${name}`;
}

await Promise.all(
  Array.from({ length: 6 }, async () => {
    while (next < urls.length) {
      const url = urls[next++];
      try {
        await cacheOne(url);
      } catch (error) {
        failed.push({
          url,
          error: error instanceof Error ? error.message : String(error),
        });
      }
    }
  }),
);

await writeFile(
  'src/data/ipa-reference-local.ts',
  `/** Generated by scripts/fetch-ipa-reference.mjs; source URLs remain in ipa-reference-audio.ts. */\nexport const ipaReferenceLocalAudio: Record<string, string> = ${JSON.stringify(local, null, 2)};\n`,
);
await writeFile(
  'public/audio/ipa-reference-manifest.json',
  JSON.stringify(
    {
      sourcePage,
      generatedAt: new Date().toISOString(),
      recordings: local,
      failed,
    },
    null,
    2,
  ),
);
await writeFile(
  'public/attribution/ipa-reference-audio.json',
  JSON.stringify(
    {
      sourcePage,
      notice:
        'Reference clips are cached from the International Phonetic Association interactive chart. The original source URL is retained for every recording.',
      recordings: Object.fromEntries(
        Object.entries(local).map(([sourceUrl, localUrl]) => [
          sourceUrl,
          { localUrl, sourceUrl },
        ]),
      ),
      failed,
    },
    null,
    2,
  ),
);
if (failed.length) {
  console.error(
    `${failed.length}/${urls.length} IPA reference recordings failed`,
  );
  for (const item of failed) console.error(item.url + ': ' + item.error);
  process.exitCode = 1;
}
console.log(
  `${Object.keys(local).length}/${urls.length} IPA reference recordings cached locally${refresh ? ' (refreshed)' : ''}.`,
);
